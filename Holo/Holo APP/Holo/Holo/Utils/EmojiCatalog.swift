    /// key 沿用知识树 v1 的历史名，避免升级后清空用户已积累的记录；现为全 App 图标选择器共享
    private static let recentKey = "topicIconRecentEmojis"
    private static let recentLimit = 16

    static func loadRecent() -> [String] {
        UserDefaults.standard.stringArray(forKey: recentKey) ?? []
    }

    /// 记录最近使用的图标（去重置顶，超出容量淘汰最旧）
    static func pushRecent(_ emoji: String) {
        var recent = loadRecent().filter { $0 != emoji }
        recent.insert(emoji, at: 0)
        if recent.count > recentLimit {
            recent = Array(recent.prefix(recentLimit))
        }
        UserDefaults.standard.set(recent, forKey: recentKey)
    }
